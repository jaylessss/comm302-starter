// Realistic candlestick generator for Supercharts screen
export function generateCandleSeries(basePrice: number, count: number = 60, volatility: number = 0.015): CandleData[] {
  const candles: CandleData[] = [];
  let currentPrice = basePrice * 0.85;
  const now = Date.now();
  const stepMs = 3600 * 1000; // 1 hour step

  for (let i = count - 1; i >= 0; i--) {
    const timeTimestamp = now - i * stepMs;
    const dateObj = new Date(timeTimestamp);
    const timeStr = `${dateObj.getMonth() + 1}/${dateObj.getDate()} ${dateObj.getHours().toString().padStart(2, '0')}:00`;

    const deltaPercent = (Math.random() - 0.48) * volatility;
    const open = currentPrice;
    const close = Math.max(open * 0.5, open * (1 + deltaPercent));
    const high = Math.max(open, close) + Math.random() * (open * volatility * 0.8);
    const low = Math.min(open, close) - Math.random() * (open * volatility * 0.8);
    const volume = Math.floor(50000 + Math.random() * 250000);

    candles.push({
      time: timeStr,
      timestamp: timeTimestamp,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });

    currentPrice = close;
  }

  // Set the last candle close close to the actual base price
  if (candles.length > 0) {
    const last = candles[candles.length - 1];
    last.close = basePrice;
    last.high = Math.max(last.high, basePrice);
    last.low = Math.min(last.low, basePrice * 0.995);
  }

  return candles;
}
